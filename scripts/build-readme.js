// Regenerates the skill index in README.md from skills/*/. `--check` fails if it's stale (CI).
import { readFileSync, writeFileSync } from 'node:fs';
import { loadLibrary } from '../src/library.js';

const file = new URL('../README.md', import.meta.url);
const lib = loadLibrary();
const byCat = Map.groupBy ? Map.groupBy(lib, (s) => s.category) : lib.reduce((m, s) => m.set(s.category, [...(m.get(s.category) ?? []), s]), new Map());
const esc = (s) => String(s).replace(/\|/g, '\\|');

const sections = [...byCat.keys()].sort().map((cat) => {
  const rows = byCat.get(cat).map((s) => {
    const icon = s.hasIcon ? `<img src="skills/${s.slug}/icon.webp" width="28" height="28" alt="">` : '';
    return `| ${icon} | [**${esc(s.title)}**](skills/${s.slug}/SKILL.md) | \`${s.slug}\` | ${esc(s.summary ?? '')} |`;
  });
  return `### ${cat}\n\n| | Skill | Name | What it handles |\n|---|---|---|---|\n${rows.join('\n')}`;
});
const block = `<!-- skills:start -->\n<!-- Generated by \`npm run readme\`. Edit skills/*/README.md instead. -->\n\n**${lib.length} skills across ${byCat.size} categories.** Each one passes the Skills Bundle build rules in CI.\n\n${sections.join('\n\n')}\n\n<!-- skills:end -->`;

const readme = readFileSync(file, 'utf8');
const next = readme.replace(/<!-- skills:start -->[\s\S]*<!-- skills:end -->/, block);
if (process.argv.includes('--check')) {
  if (next !== readme) { console.error('README skill index is out of date. Run: npm run readme'); process.exit(1); }
  console.log('README index up to date.');
} else {
  writeFileSync(file, next);
  console.log(`README index: ${lib.length} skills.`);
}
